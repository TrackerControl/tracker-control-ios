function normalizeLocale(value) {
  return value === 'da' ? 'da' : 'en';
}

function interpolate(template, values = {}) {
  return template.replace(/\{\{([\w]+)\}\}/g, (_, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : `{{${key}}}`
  );
}

function createTranslator(locale = 'en') {
  const selected = normalizeLocale(locale);
  return (key, values) => interpolate(
    selected === 'da' && Object.prototype.hasOwnProperty.call(da, key) ? da[key] : key,
    values
  );
}

function formatDate(value, locale = 'en', options = { day: 'numeric', month: 'short', year: 'numeric' }) {
  const date = value instanceof Date ? value : new Date(value);
  if (!value || Number.isNaN(date.getTime())) return null;
  return date.toLocaleDateString(normalizeLocale(locale) === 'da' ? 'da-DK' : 'en-GB', options);
}

function formatDateTime(value, locale = 'en') {
  const date = value instanceof Date ? value : new Date(value);
  if (!value || Number.isNaN(date.getTime())) return null;
  return date.toLocaleString(normalizeLocale(locale) === 'da' ? 'da-DK' : 'en-GB');
}

function localeForRequest(req) {
  if (req && (req.locale === 'da' || req.locale === 'en'))
    return { locale: req.locale, fromQuery: false };
  const original = req && (req.originalUrl || req.url || '');
  const path = new URL(original, 'http://localhost').pathname;
  return { locale: path === '/da' || path.startsWith('/da/') ? 'da' : 'en', fromQuery: false };
}

function publicPath(pathname) {
  if (pathname === '/da') return '/';
  if (pathname.startsWith('/da/')) return pathname.slice(3) || '/';
  return pathname || '/';
}

function isPublicLocalizedPath(pathname, method = 'GET') {
  if (!pathname || !pathname.startsWith('/da')) return false;
  const path = pathname.replace(/\/+$/, '') || '/da';
  const publicPathname = path === '/da' ? '/' : path.slice(3);
  if (!['GET', 'HEAD', 'POST'].includes(method)) return false;
  if (method === 'POST') return /^\/analysis\/[^/]+$/.test(publicPathname);
  return publicPathname === '/'
    || ['/about', '/statistics', '/trackers', '/companies', '/search'].includes(publicPathname)
    || /^\/(?:analysis|request|tracker|company)\/[^/]+$/.test(publicPathname);
}

function stripLocalePrefix(url) {
  const parsed = new URL(url || '/', 'http://localhost');
  parsed.pathname = publicPath(parsed.pathname);
  return parsed.pathname + parsed.search + parsed.hash;
}

function localUrl(path, locale = 'en', currentPath = '/') {
  const raw = path || currentPath;
  if (/^[a-z][a-z0-9+.-]*:/i.test(raw) || raw.startsWith('//')) return raw;
  const parsed = new URL(raw.startsWith('?') || raw.startsWith('#')
    ? `${currentPath || '/'}${raw}`
    : raw, 'http://localhost');
  let pathname = publicPath(parsed.pathname);
  if (normalizeLocale(locale) === 'da') {
    pathname = pathname === '/' ? '/da/' : `/da${pathname}`;
  }
  return pathname + parsed.search + parsed.hash;
}

function languageUrl(originalUrl, locale) {
  const parsed = new URL(originalUrl || '/', 'http://localhost');
  parsed.searchParams.delete('lang');
  return localUrl(
    publicPath(parsed.pathname) + parsed.search + parsed.hash,
    locale,
    publicPath(parsed.pathname)
  );
}

function canonicalUrl(base, path, locale, extraQuery = {}) {
  const parsed = new URL(path || '/', 'http://localhost');
  const params = new URLSearchParams(parsed.search);
  for (const [key, value] of Object.entries(extraQuery)) params.set(key, value);
  const pathname = localUrl(parsed.pathname, locale);
  const query = params.toString();
  return base.replace(/\/+$/, '') + pathname + (query ? `?${query}` : '');
}

